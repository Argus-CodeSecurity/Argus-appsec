"""Generate ``SUMMARY.md`` for a set (``benchmarks/results/<set>/``) from its results JSON."""

from __future__ import annotations

from pathlib import Path
from typing import Any

from benchmarks.public.report import pct

TOOLS = ("nephilex", "bandit", "semgrep")
_HEAD = (
    "| Tool | Subset | Cases | Detected | Recall | Flagged after fix | Still flagged "
    "| Fix-aware detected | Fix-aware recall | Precision proxy |"
)
_SEP = "|---|---|---|---|---|---|---|---|---|---|"


def _ok(doc: dict[str, Any]) -> list[str]:
    return [t for t in TOOLS if doc["tools"].get(t, {}).get("status") == "ok"]


def _row(tool: str, subset: str, m: dict[str, Any], unit: str = "cases") -> str:
    return (
        f"| {tool} | {subset} | {m[unit]} | {m['detected']} | {pct(m['recall'])} | "
        f"{m['flagged_after_fix']} | {m['still_flagged']} | {m['fix_aware_detected']} | "
        f"{pct(m['fix_aware_recall'])} | {pct(m['precision_proxy'])} |"
    )


def headline(doc: dict[str, Any], mode: str) -> list[str]:
    lines = [_HEAD, _SEP]
    for tool in _ok(doc):
        met = doc["tools"][tool]["metrics"][mode]
        lines.append(_row(tool, "all applicable", met["overall"]))
        for fam, m in met["by_language_family"].items():
            lines.append(_row(tool, fam, m))
    return lines


def advisories(doc: dict[str, Any], mode: str) -> list[str]:
    lines = [_HEAD.replace("| Cases |", "| Advisories |"), _SEP]
    for tool in _ok(doc):
        m = doc["tools"][tool]["metrics"][mode]["advisories"]
        lines.append(_row(tool, "all applicable", m, unit="advisories"))
    return lines


def breakdown(doc: dict[str, Any], mode: str, key: str, title: str) -> list[str]:
    tools = _ok(doc)
    groups: dict[str, int] = {}
    for tool in tools:
        for g, m in doc["tools"][tool]["metrics"][mode][key].items():
            groups[g] = max(groups.get(g, 0), int(m["cases"]))
    head = f"| {title} | Cases | " + " | ".join(f"{t} detected / flagged after fix" for t in tools)
    lines = [head + " |", "|---|---|" + "---|" * len(tools)]
    for g, n in groups.items():
        cells = []
        for tool in tools:
            m = doc["tools"][tool]["metrics"][mode][key].get(g)
            if m is None:
                cells.append("n/a")
            else:
                cells.append(f"{m['detected']}/{m['cases']} / {m['flagged_after_fix']}")
        lines.append(f"| {g} | {n} | " + " | ".join(cells) + " |")
    return lines


def sensitivity(doc: dict[str, Any]) -> list[str]:
    windows = [*doc["scoring"]["sensitivity_windows"], doc["scoring"]["window"]]
    windows = sorted(set(windows))
    lines = [
        "| Tool | Mode | "
        + " | ".join(f"Window {w}: detected / flagged after fix" for w in windows)
        + " |",
        "|---|---|" + "---|" * len(windows),
    ]
    for tool in _ok(doc):
        entry = doc["tools"][tool]
        for mode in doc["scoring"]["modes"]:
            cells = []
            for w in windows:
                if w == doc["scoring"]["window"]:
                    m = entry["metrics"][mode]["overall"]
                else:
                    m = entry["window_sensitivity"][str(w)][mode]
                cells.append(f"{m['detected']}/{m['cases']} / {m['flagged_after_fix']}")
            lines.append(f"| {tool} | {mode} | " + " | ".join(cells) + " |")
    return lines


def runs(doc: dict[str, Any]) -> list[str]:
    lines = ["| Tool | Version | Run date (UTC) | Seconds | Command |", "|---|---|---|---|---|"]
    for tool in TOOLS:
        entry = doc["tools"].get(tool) or {}
        if entry.get("status") != "ok":
            lines.append(f"| {tool} | not run | | | {entry.get('reason', '')} |")
            continue
        run = entry["run"]
        cmd = " ".join(run.get("command", []))
        lines.append(
            f"| {tool} | {run.get('version')} | {run.get('started_at')} | "
            f"{run.get('seconds')} | `{cmd}` |"
        )
    return lines


def write_summary(
    doc: dict[str, Any],
    path: Path,
    title: str = "Held-out benchmark: real fix commits",
    note: str = "",
    cases: list[dict[str, Any]] | None = None,
    per_case: dict[str, dict[str, Any]] | None = None,
) -> Path:
    man = doc["manifest"]
    src = doc["nephilex_source"]
    out = [
        f"# {title}",
        "",
        "Generated by `python benchmarks/heldout/run.py`; method and caveats in "
        "`docs/benchmarks.md`. Do not edit by hand.",
        "",
        *([f"**{note}**", ""] if note else []),
        f"- Nephilex source: commit `{src['commit']}`"
        + (" (src/nephilex modified)" if src.get("src_nephilex_modified") else ""),
        f"- Manifest: `{man['path']}` (sha256 `{man['sha256']}`), selected {man['selected_at']}",
        f"- Cases: {man['cases_selected']} selected, {man['cases_scored']} scored, "
        f"{len(man['cases_excluded'])} excluded; {man['advisories_scored']} advisories",
        f"- Languages: {', '.join(f'{k} {v}' for k, v in man['languages'].items())}",
        f"- Ecosystems: {', '.join(f'{k} {v}' for k, v in man['ecosystems'].items())}",
        f"- Window: {doc['scoring']['window']} lines around the changed lines",
        "",
        "## Runs",
        "",
        *runs(doc),
        "",
    ]
    sem = doc["tools"].get("semgrep", {}).get("run", {})
    for rs in sem.get("rulesets") or []:
        out.append(
            f"- Semgrep ruleset `{rs['ruleset']}`: {rs['ruleset_rules']} rules, sha256 "
            f"`{rs['ruleset_sha256']}`, fetched {rs['ruleset_fetched_at']}"
        )
    if man["cases_excluded"]:
        out += ["", "## Excluded cases", "", "| Case | Reason |", "|---|---|"]
        out += [f"| {k} | {v} |" for k, v in man["cases_excluded"].items()]
    for mode, heading in (
        ("mapped", "CWE match, mapped (primary)"),
        ("strict", "CWE match, strict"),
        ("any", "Any finding in the changed lines (CWE-agnostic)"),
    ):
        out += ["", f"## {heading}", "", *headline(doc, mode)]
    out += ["", "## Per advisory (mapped)", "", *advisories(doc, "mapped")]
    out += ["", "## Per advisory (any finding)", "", *advisories(doc, "any")]
    out += ["", "## By CWE (mapped)", "", *breakdown(doc, "mapped", "by_cwe", "CWE")]
    out += ["", "## By CWE (any finding)", "", *breakdown(doc, "any", "by_cwe", "CWE")]
    out += ["", "## By language (mapped)", "", *breakdown(doc, "mapped", "by_language", "Language")]
    out += [
        "",
        "## By ecosystem (mapped)",
        "",
        *breakdown(doc, "mapped", "by_ecosystem", "Ecosystem"),
    ]
    out += ["", "## Window sensitivity", "", *sensitivity(doc), ""]
    if cases is not None and per_case is not None:
        out += ["## Per case", "", *case_table(doc, cases, per_case), ""]
    path.write_text("\n".join(out), encoding="utf-8", newline="\n")
    return path


def _mark(outcome: dict[str, Any] | None) -> str:
    """``D`` detected, ``F`` flagged after the fix, ``-`` neither, blank if n/a."""
    if outcome is None:
        return ""
    marks = ("D" if outcome["detected"] else "") + ("F" if outcome["flagged_after_fix"] else "")
    return marks or "-"


def case_table(
    doc: dict[str, Any], cases: list[dict[str, Any]], per_case: dict[str, dict[str, Any]]
) -> list[str]:
    """One row per scored case: mapped and any-finding outcome for each tool.

    For a set that is studied (the development set), so every miss has a row.
    """
    tools = _ok(doc)
    head = "| Case | Language | CWEs | File | " + " | ".join(f"{t} mapped / any" for t in tools)
    lines = [
        "`D` detected, `F` flagged after the fix, `-` neither; blank when the tool "
        "does not apply. Findings for each case are in `cases/<case>.json`.",
        "",
        head + " |",
        "|---|---|---|---|" + "---|" * len(tools),
    ]
    for c in cases:
        cells = []
        for tool in tools:
            entry = per_case.get(tool, {}).get(c["case_id"])
            if entry is None:
                cells.append("")
            else:
                cells.append(f"{_mark(entry.get('mapped'))} / {_mark(entry.get('any'))}")
        cwes = ", ".join(str(x) for x in c["label_cwes"])
        lines.append(
            f"| {c['case_id']} | {c['language']} | {cwes} | `{c['repo']}/{c['path_patched']}` | "
            + " | ".join(cells)
            + " |"
        )
    return lines
